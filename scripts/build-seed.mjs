import { writeFile } from 'node:fs/promises';
import { SOURCES } from '../public/data.js';

// Versioned editorial seed. It contains public website descriptions only.
// Preview display labels are mapped explicitly to portable production values.
const countries = {'Portugal':'PT','Spain':'ES','Ireland':'IE','Israel':'IL','South Korea':'KR','Austria':'AT','Belgium':'BE','Brazil':'BR','Chile':'CL','Colombia':'CO','Denmark':'DK','Finland':'FI','France':'FR','Germany':'DE','Hong Kong':'HK','Italy':'IT','Japan':'JP','Kenya':'KE','Mexico':'MX','Norway':'NO','South Africa':'ZA','Sweden':'SE','Switzerland':'CH','United Kingdom':'GB',Australia:'AU','United States':'US',Canada:'CA',Hungary:'HU',Netherlands:'NL','New Zealand':'NZ'};
const languageCodes = {English:'en',Norwegian:'no',Danish:'da',Finnish:'fi',Welsh:'cy',Dutch:'nl',Indonesian:'id',Malay:'ms',Bosnian:'bs','Mandarin Chinese':'zh',Czech:'cs',Estonian:'et',Farsi:'fa',French:'fr',German:'de',Hebrew:'he',Italian:'it',Japanese:'ja',Korean:'ko',Lao:'lo',Latvian:'lv',Mongolian:'mn',Portuguese:'pt',Russian:'ru',Slovenian:'sl',Spanish:'es',Swedish:'sv',Thai:'th',Turkish:'tr',Vietnamese:'vi'};
const coverageRegions = {'International':'global','Europe':'region:Europe','Africa':'region:Africa','Asia':'region:Asia','North America':'region:North America','South America':'region:South America','Oceania':'region:Oceania','Scotland':'GB-SCT','England and Wales':'GB-ENG-WLS','Northern Ireland':'GB-NIR'};
const quote = value => `'${String(value).replaceAll("'", "''")}'`;
const array = values => `array[${values.map(quote).join(',')}]::text[]`;
const required = (map, value, field) => {
  if (!map[value]) throw new Error(`Unmapped ${field}: ${value}`);
  return map[value];
};

const values = SOURCES.map(s => {
  const url = new URL(s.url);
  if (!['http:','https:'].includes(url.protocol) || url.username || url.password) throw new Error(`Unsafe source URL: ${s.id}`);
  const coverage=s.coverage.map(c=>coverageRegions[c] || required(countries,c,'coverage'));
  return `(${[
    quote(s.id),quote(s.name),quote(s.url),quote(url.hostname.toLowerCase().replace(/^www\./,'')),
    quote(s.owner),quote(s.about),s.logo?quote(s.logo):'null',quote(required(countries,s.country,'country')),
    array(coverage),array(s.types),array(s.content),array(s.methods),array(s.topics),
    array(s.languages.map(l=>required(languageCodes,l,'language'))),quote(s.access.toLowerCase()),
    quote(s.checked+'T00:00:00Z')+'::timestamptz',quote('editor_added'),quote('published'),'now()'
  ].join(',')})`;
});

const sql=`-- Generated by npm run db:seed from public/data.js. Review and commit together.
-- Public, editor-added records. No representatives, contacts, votes or verified
-- ownership are invented. Existing profiles and signals are never overwritten.
insert into public.sources (
  slug,name,website_url,canonical_domain,publisher,about,logo_path,country_code,coverage,
  kinds,content_types,methods,topics,research_languages,access_type,checked_at,
  provenance,status,published_at
)
values
${values.join(',\n')}
on conflict (slug) do nothing;
`;
await writeFile(new URL('../supabase/seed.sql',import.meta.url), sql+`\ninsert into public.source_signals(source_id)
select id from public.sources where slug in (${SOURCES.map(s=>quote(s.id)).join(',')})
on conflict (source_id) do nothing;\n`);
console.log(`Prepared ${SOURCES.length} public editorial records; no verified signals or member accounts.`);
